#!/bin/sh
# mksyms.sh — the kernel's symbol table, as NASM source (Chapter 10).
#
#   tools/mksyms.sh build/kernel0.elf >build/symtab.asm
#   tools/mksyms.sh >build/symtab0.asm        (an empty table)
#
# Lists every function in the kernel (nm types t and T, except the
# linker script's __ names), sorted by address, as three arrays in
# section .ksyms: ksyms_count, ksyms_addr[] and ksyms_name[]
# (kernel/ksyms.h). The kernel is linked twice: first with an empty
# table, to learn where the functions are, then with the real one.
# linker.ld puts .ksyms after everything else that is loaded, so the
# second link moves no function; the Makefile checks that.
set -e

if [ $# -gt 0 ]; then
    nm -n --defined-only "$1"
fi | awk '
BEGIN { n = 0 }
($2 == "t" || $2 == "T") && $3 !~ /^__/ { addr[n] = $1; name[n] = $3; n++ }
END {
    print "; generated by tools/mksyms.sh: do not edit"
    print "section .ksyms progbits alloc noexec nowrite align=4"
    print "global ksyms_count, ksyms_addr, ksyms_name"
    printf "ksyms_count: dd %d\n", n
    print "ksyms_addr:"
    for (i = 0; i < n; i++)
        printf "    dd 0x%s\n", addr[i]
    print "ksyms_name:"
    for (i = 0; i < n; i++)
        printf "    dd .s%d\n", i
    for (i = 0; i < n; i++)
        printf ".s%d: db \"%s\", 0\n", i, name[i]
}'
